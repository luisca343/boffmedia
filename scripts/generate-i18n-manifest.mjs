#!/usr/bin/env node
// Discovers every locale namespace file and writes src/i18n/manifest.generated.ts.
// Run via `pnpm generate:i18n`; `pnpm check:i18n` fails when the file is stale.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const ES_ROOT = "apps/web/locales/es";
const OUT = "apps/web/src/i18n/manifest.generated.ts";

export function namespaceFiles(dir = ES_ROOT, base = "", out = []) {
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) namespaceFiles(path, `${base}${entry}/`, out);
    else if (entry.endsWith(".json")) out.push(`${base}${entry}`);
  }
  return out;
}

/** The top-level keys a namespace file contributes to the merged message tree. */
export function rootKeys(relPath) {
  return Object.keys(JSON.parse(readFileSync(join(ES_ROOT, relPath), "utf8")));
}

export function buildManifest() {
  const files = namespaceFiles();
  const roots = Object.fromEntries(files.map((f) => [f, rootKeys(f)]));
  return { files, roots };
}

export function render({ files, roots }) {
  const lines = [
    "// GENERATED by scripts/generate-i18n-manifest.mjs — do not edit.",
    "// Run `pnpm generate:i18n` after adding or removing a locale file.",
    "",
    "/** Every namespace file under locales/<locale>/, relative to that directory. */",
    "export const ALL_NAMESPACES = [",
    ...files.map((f) => `  ${JSON.stringify(f)},`),
    "] as const;",
    "",
    "export type Namespace = (typeof ALL_NAMESPACES)[number];",
    "",
    "/** Top-level message keys each file contributes — used by check:i18n to verify scoping. */",
    "export const NAMESPACE_ROOTS: Record<Namespace, readonly string[]> = {",
    ...files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(roots[f])},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

// pathToFileURL, not string interpolation: the repo path contains a space, which
// import.meta.url percent-encodes and process.argv[1] does not.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest = buildManifest();
  writeFileSync(OUT, render(manifest));
  console.log(`i18n manifest: ${manifest.files.length} namespace files → ${OUT}`);
}
