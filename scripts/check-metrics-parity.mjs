#!/usr/bin/env node
/**
 * X11. Keeps the Grafana dashboard and the alert rules pointed at metrics the
 * API actually registers.
 *
 * The finding was "Prometheus/Grafana rollout is half done: alert rules
 * unchecked, dashboard JSON not verified against live metrics". Checking it by
 * hand once would leave it half done again the first time a metric is renamed —
 * and the failure is silent in the worst possible way, because a PromQL
 * expression naming a metric that does not exist returns an empty series, and
 * an empty series renders as a flat line at zero. A dashboard panel and an
 * alert that are both watching nothing look exactly like a healthy system.
 *
 * WHAT IT CHECKS
 *
 *   1. Every metric name in docs/grafana-dashboard-boffmedia.json and
 *      docs/grafana/alerts-boffmedia.yaml is either registered by the API or
 *      owned by a known exporter.
 *   2. Every metric the API registers is referenced by at least one panel or
 *      rule. Instrumentation nobody looks at is the other half of this finding:
 *      db-metrics.ts and retention.service.ts shipped four metrics and the
 *      dashboard had never heard of any of them.
 *
 * Anything matching neither list fails as unknown, which is what catches a
 * typo — the case that motivates the whole script.
 */
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DASHBOARD = 'docs/grafana-dashboard-boffmedia.json';
const ALERTS = 'docs/grafana/alerts-boffmedia.yaml';

const failures = [];

/**
 * Metrics that come from something other than our code, and so cannot be
 * checked against this repository. Prefixes, because each exporter owns a whole
 * namespace.
 *
 *   mysql_   mysqld_exporter        node_     node_exporter
 *   process_ prom-client's default collectors (resident memory, cpu, fds)
 *   nodejs_  same, the Node-specific half
 *   container_ cAdvisor
 *   up, scrape_  Prometheus itself
 */
const EXPORTER_PREFIXES = ['mysql_', 'node_', 'process_', 'nodejs_', 'container_', 'scrape_'];
const EXPORTER_EXACT = new Set(['up']);

/** PromQL functions and keywords that lex identically to a metric name. */
const PROMQL_WORDS = new Set([
  'sum', 'rate', 'irate', 'increase', 'avg', 'min', 'max', 'count', 'topk',
  'bottomk', 'histogram_quantile', 'quantile', 'clamp_min', 'clamp_max',
  'vector', 'time', 'by', 'without', 'or', 'and', 'unless', 'on', 'ignoring',
  'group_left', 'group_right', 'delta', 'idelta', 'absent', 'round', 'abs',
  'le', 'route', 'status_code', 'job', 'path', 'operation', 'instance',
]);

/** Metric names the API registers, read from the prom-client call sites. */
function registeredMetrics() {
  const files = [
    'apps/api/src/_utils/metrics/metrics.middleware.ts',
    'apps/api/src/_utils/metrics/db-metrics.ts',
    'apps/api/src/api/retention/retention.service.ts',
  ];
  const found = new Map(); // name -> kind
  for (const file of files) {
    const text = readFileSync(join(ROOT, file), 'utf8');
    // `new Histogram({ name: 'x', ... })` / Counter / Gauge
    for (const m of text.matchAll(
      /new\s+(Histogram|Counter|Gauge)\s*\(\s*\{[\s\S]{0,200}?name:\s*'([a-z][a-z0-9_]*)'/g,
    )) {
      found.set(m[2], m[1]);
    }
  }
  if (found.size === 0) {
    failures.push(
      'No prom-client metric registrations found in the API. Either the metrics moved, or ' +
        'this gate is now comparing the dashboard against an empty list -- which passes ' +
        'everything.',
    );
  }
  return found;
}

/** Every metric-shaped identifier used in an expression, `_bucket`/`_sum`/`_count` folded back. */
function metricsInExpr(expr, into, where) {
  // Strip label matchers first: `{status_code=~"5.."}` contains no metric names
  // but does contain identifiers.
  const bare = expr.replace(/\{[^}]*\}/g, ' ').replace(/"[^"]*"/g, ' ');
  for (const m of bare.matchAll(/\b([a-z][a-z0-9_]{3,})\b/g)) {
    let name = m[1];
    if (PROMQL_WORDS.has(name)) continue;
    // Histogram/summary suffixes are generated by prom-client, not registered.
    name = name.replace(/_(bucket|sum|count)$/, '');
    if (!into.has(name)) into.set(name, new Set());
    into.get(name).add(where);
  }
}

function dashboardExprs() {
  const json = JSON.parse(readFileSync(join(ROOT, DASHBOARD), 'utf8'));
  const out = [];
  const walk = (o) => {
    if (!o || typeof o !== 'object') return;
    if (Array.isArray(o)) return o.forEach(walk);
    if (typeof o.expr === 'string') out.push(o.expr);
    for (const k of Object.keys(o)) walk(o[k]);
  };
  walk(json);
  if (out.length === 0) failures.push(`${DASHBOARD}: no panel expressions found.`);
  return out;
}

function alertExprs() {
  // Read as text rather than parsed YAML: the repo has no YAML parser as a
  // dependency, the expressions are the only thing needed, and every one of
  // them sits on an `expr:` key.
  const text = readFileSync(join(ROOT, ALERTS), 'utf8');
  const out = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^(\s*)expr:\s*(.*)$/);
    if (!m) continue;
    const [, indent, rest] = m;
    if (rest.trim() === '>-' || rest.trim() === '>' || rest.trim() === '|') {
      // Block scalar: take the more-indented lines that follow.
      const buf = [];
      for (let j = i + 1; j < lines.length; j++) {
        if (lines[j].trim() === '') continue;
        const lead = lines[j].match(/^\s*/)[0].length;
        if (lead <= indent.length) break;
        buf.push(lines[j].trim());
      }
      out.push(buf.join(' '));
    } else {
      out.push(rest.trim());
    }
  }
  if (out.length === 0) failures.push(`${ALERTS}: no expr: entries found.`);
  // The placeholder must survive: a file committed with a real UID would mean
  // one server's UID is baked into the repo and every other server silently
  // provisions rules against a datasource that does not exist there.
  if (!text.includes('PROMETHEUS_DS_UID')) {
    failures.push(
      `${ALERTS}: the PROMETHEUS_DS_UID placeholder is gone. A real datasource UID is ` +
        `per-server; substitute it at install time, not in the repository.`,
    );
  }
  return out;
}

const registered = registeredMetrics();
const used = new Map(); // metric -> Set<where>

for (const e of dashboardExprs()) metricsInExpr(e, used, 'dashboard');
for (const e of alertExprs()) metricsInExpr(e, used, 'alerts');

// 1. everything referenced must be explicable
const unknown = [];
for (const [name, where] of used) {
  if (registered.has(name)) continue;
  if (EXPORTER_EXACT.has(name)) continue;
  if (EXPORTER_PREFIXES.some((p) => name.startsWith(p))) continue;
  unknown.push(`${name}  (used in: ${[...where].join(', ')})`);
}
if (unknown.length) {
  failures.push(
    `${unknown.length} metric name(s) referenced by a panel or an alert that the API does not\n` +
      `  register and no known exporter provides. A PromQL name that does not exist returns an\n` +
      `  empty series, which renders as a flat zero -- indistinguishable from healthy:\n` +
      unknown.map((u) => `    ${u}`).join('\n'),
  );
}

// 2. everything registered should be watched
const unwatched = [...registered.keys()].filter((n) => !used.has(n));
if (unwatched.length) {
  failures.push(
    `${unwatched.length} metric(s) the API registers that no panel and no alert reads:\n` +
      unwatched.map((n) => `    ${n} (${registered.get(n)})`).join('\n') +
      `\n  Add a panel or a rule, or delete the instrumentation. Shipping a metric nobody\n` +
      `  looks at is the half-done state this check exists to end.`,
  );
}

console.log(
  `Checked ${used.size} metric reference(s) across the dashboard and the alert rules ` +
    `against ${registered.size} registered by the API.\n`,
);

if (failures.length) {
  console.error('FAIL -- metrics parity:\n');
  for (const f of failures) console.error(`  ${f}\n`);
  process.exit(1);
}

console.log('OK -- every panel and alert reads a metric that exists, and every metric is read.\n');
